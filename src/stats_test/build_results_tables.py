#!/usr/bin/env python3
"""
build_results_tables.py
-----------------------
Emits all_runs/tables_folder_label.tex: three per-query-field result tables
(T--, TD-, TDN) plus a cross-query-field summary table, covering the
folder-label-augmentation batch from run_all_folders_augmented_experiments.py.

Why one table per query field: crossing query field into the columns of a
single table produced something too wide to read. Splitting by query field
lets the columns carry the axis that actually varies here -- how much
folder-label augmentation is applied, and whether the query is expanded.

Column layout (6 numeric columns + one shared margin column):

    Base | +HyDE || FL-aug: partner (Base, +CT) || FL-aug: doc field (Base, +HyDE, +CT) | +-

  Base              plain query, plain folder label
  +HyDE             query + hypothetical documents + hypothetical folder label
                    (run_query_augmentated_experiments.py's 'AUG' variant)
  FL-aug: partner   the ALLFL partner ranker's labels are augmented; the main
                    ranker's own 'folderlabel' field is not  (*.TOFS.*.FLAug)
  FL-aug: doc field the main ranker's own 'folderlabel' field is augmented
                    (*.TOFAUGS.*); for hybrid rows the partner is augmented too
  +CT               query + the topic's core themes + related concepts

The grid is deliberately sparse. The two FL-aug blocks are mutually exclusive
except for the hybrid configs, and '+CT' only ever pairs with an augmented
folder label. Cells that were never run are '---', not zero -- including the
'FL-aug: doc field / +HyDE' column, which is pending
run_table_completion_experiments.py (group FLDOC).

NOTE ON +HyDE vs +CT: these are two different query expansions, not two names
for one. The older tables_of_results.tex captions describe '+AUG' as "expanded
with core themes and related concepts", which is CT's definition, not HyDE's.

Run from the project root:
    python src/stats_test/build_results_tables.py            # tables fragment only
    python src/stats_test/build_results_tables.py --preview  # + standalone wrapper
    python src/stats_test/build_results_tables.py --compile  # + render it to PDF

The fragment (tables_folder_label.tex) is what the paper \\input's. The preview
wrapper (tables_folder_label_preview.tex) is a throwaway document that exists
only to render the fragment for eyeballing; it is not part of the paper.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import tempfile
from collections import OrderedDict

PROJECT_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
RUNS_DIR = os.path.join(PROJECT_ROOT, 'all_runs')
OUT_PATH = os.path.join(RUNS_DIR, 'tables_folder_label.tex')
PREVIEW_PATH = os.path.join(RUNS_DIR, 'tables_folder_label_preview.tex')
PREVIEW_PDF = os.path.join(RUNS_DIR, 'tables_folder_label_preview.pdf')

# Standalone wrapper for eyeballing the tables.
#
# Deliberately ONE-column, even though the paper is two-column. In a twocolumn
# document a table* (full-width float) can never be placed on the page that
# declares it -- LaTeX defers all of them, so the preview opens on a blank page
# and the tables drift out of order. In a onecolumn document table* degrades to
# table and each one lands where it was declared, which is what you want when
# checking whether a table fits and reads.
#
# Consequence to keep in mind: the summary table sizes itself to \columnwidth,
# which here equals the full text width. In the real two-column paper it will
# render at half this width.
PREVIEW_TEMPLATE = r"""%% Generated by src/stats_test/build_results_tables.py -- do not edit by hand.
%% Standalone preview wrapper. The tables themselves live in %(fragment)s and
%% are meant to be \input into the paper; this file only renders them.
%% One-column on purpose -- see PREVIEW_TEMPLATE in build_results_tables.py.
\documentclass[a4paper]{article}
\usepackage[margin=1.5cm,landscape]{geometry}
\usepackage{graphicx}
\pagestyle{empty}
%% Preview-only float relaxation. The default parameters reserve 20%% of every
%% page for body text, and this document has almost none, so all four tables
%% would defer to the end. These renewals let them sit where they are declared.
%% They affect this wrapper only -- the tables keep their own [t] placement.
\renewcommand{\topfraction}{1.0}
\renewcommand{\bottomfraction}{1.0}
\renewcommand{\textfraction}{0.0}
\renewcommand{\floatpagefraction}{0.0}
\setcounter{topnumber}{10}
\setcounter{totalnumber}{10}
\begin{document}
\noindent\textbf{Preview:} folder-label augmentation results, rendered from
\texttt{%(fragment_tt)s}. Not part of the paper; one-column, so the summary
table appears wider here than it will in the paper.
\input{%(fragment)s}
\null\clearpage
\end{document}
"""

# Query field -> (plain tag, HyDE tag, CT tag). The augmented tags drop the
# 4-char padded tag's last character and append the variant, matching
# run_query_augmentated_experiments.py and run_all_folders_augmented_experiments.py.
QUERY_FIELDS = OrderedDict([
    ('T--',  {'label': 'Title (T{-}{-})',                 'hyde': 'T--AUG', 'ct': 'T--CT'}),
    ('TD-',  {'label': 'Title+Desc (TD-)',                'hyde': 'TD-AUG', 'ct': 'TD-CT'}),
    ('TDN',  {'label': 'Title+Desc+Narr (TDN)',           'hyde': 'TDNAUG', 'ct': 'TDNCT'}),
])

# group: 'A' hybrid (main ranker + separate ALLFL partner)
#        'B' standalone (main ranker only)
#        'C' pure ALLFL baseline (the ALLFL ranker is the only ranker)
# block: row-grouping for the table body, in emission order.
ROWS = [
    # single-field ablation
    {'suffix': 'B.--F-.-.-',      'group': 'B', 'block': 'single'},
    # standalone multi-field
    {'suffix': 'B.TOFS.-.-',      'group': 'B', 'block': 'standalone'},
    {'suffix': 'L.TOFS.mx--2.-',  'group': 'B', 'block': 'standalone'},
    {'suffix': 'C.TOFS.-.-',      'group': 'B', 'block': 'standalone'},
    {'suffix': 'E.TOFS.-.-',      'group': 'B', 'block': 'standalone'},
    {'suffix': 'Z.TOFS.-.-',      'group': 'B', 'block': 'standalone'},
    {'suffix': 'W.TOFS.-.-',      'group': 'B', 'block': 'standalone'},
    # hybrid
    {'suffix': 'V.TOFS.mx--2.b',  'group': 'A', 'block': 'hybrid'},
    {'suffix': 'X.TOFS.mx--2.b',  'group': 'A', 'block': 'hybrid'},
    {'suffix': 'W.TOFS.-.c',      'group': 'A', 'block': 'hybrid'},
    {'suffix': 'W.TOFS.s---2.c',  'group': 'A', 'block': 'hybrid'},
    # pure ALLFL baselines
    {'suffix': '-.----.-.b',      'group': 'C', 'block': 'allfl'},
    {'suffix': '-.----.-.c',      'group': 'C', 'block': 'allfl'},
    {'suffix': '-.----.-.e',      'group': 'C', 'block': 'allfl'},
]

BLOCK_ORDER = ['single', 'standalone', 'hybrid', 'allfl']

COLUMNS = ['base', 'hyde', 'part', 'part_ct', 'full', 'hyde_full', 'full_ct']

COLUMN_SHORT = {
    'base': 'Base', 'hyde': '+HyDE',
    'part': 'FL-part', 'part_ct': 'FL-part +CT',
    'full': 'FL-doc', 'hyde_full': 'FL-doc +HyDE', 'full_ct': 'FL-doc +CT',
}

# Named ids for the four plain ALLFL baselines that were never generated.
PENDING_IDS = {
    'U5.T--.-.----.-.b': 16, 'U5.T--.-.----.-.e': 17,
    'U5.TDN.-.----.-.b': 76, 'U5.TDN.-.----.-.e': 77,
}

HYDE_TAGS = ('T--AUG', 'TD-AUG', 'TDNAUG')


def pending_hint(name: str):
    """How to generate a run the tables want but all_runs/ does not have, or
    None if the absence is not something a known script would fill.

    Hints are deduplicated per table, so a whole missing column costs one
    comment line rather than one per row.
    """
    if name in PENDING_IDS:
        return (f'plain ALLFL baselines: python run_new_experiments.py '
                f'{" ".join(str(i) for i in sorted(PENDING_IDS.values()))} (from /src)')
    is_hyde = any(f'.{tag}.' in name for tag in HYDE_TAGS)
    if not is_hyde:
        return None
    if 'FAUG' in name:
        return ('FL-aug doc. field x +HyDE: python -m '
                'src.llm_experiments.runs.run_table_completion_experiments FLDOC')
    if '.-.----.-.' in name:
        return ('HyDE ALLFL baselines: python -m '
                'src.llm_experiments.runs.run_table_completion_experiments ALLFL')
    return None


# ---------------------------------------------------------------------------
# Run-name construction (mirrors run_all_folders_augmented_experiments.py)
# ---------------------------------------------------------------------------

def augmented_fields_code(suffix: str) -> str:
    """'TOFS' -> 'TOFAUGS', '--F-' -> '--FAUG-' in the fields-code slot."""
    parts = suffix.split('.')
    parts[1] = parts[1].replace('F', 'FAUG')
    return '.'.join(parts)


def run_names(row, qf: str) -> dict:
    """Column key -> run folder name, for the columns this row's group has.

    Columns a group structurally cannot have are simply absent from the dict
    (distinct from present-but-not-yet-run, which surfaces as a missing folder).
    """
    tags = QUERY_FIELDS[qf]
    suffix, group = row['suffix'], row['group']
    faug = augmented_fields_code(suffix)

    names = {
        'base': f'U5.{qf}.{suffix}',
        'hyde': f"U5.{tags['hyde']}.{suffix}",
    }
    if group == 'A':
        # Partner-only augmentation and full augmentation are distinct runs.
        names['part'] = f'U5.{qf}.{suffix}.FLAug'
        names['part_ct'] = f"U5.{tags['ct']}.{suffix}.FLAug"
        names['full'] = f'U5.{qf}.{faug}.FLAug'
        names['hyde_full'] = f"U5.{tags['hyde']}.{faug}.FLAug"
        names['full_ct'] = f"U5.{tags['ct']}.{faug}.FLAug"
    elif group == 'B':
        # No ALLFL partner exists, so only the doc-field columns apply.
        names['full'] = f'U5.{qf}.{faug}'
        names['hyde_full'] = f"U5.{tags['hyde']}.{faug}"
        names['full_ct'] = f"U5.{tags['ct']}.{faug}"
    else:  # group C: the ALLFL ranker is the only ranker, so its augmented
        # run is a partner-side augmentation; there is no main ranker field.
        names['part'] = f'U5.{qf}.{suffix}.FLAug'
        names['part_ct'] = f"U5.{tags['ct']}.{suffix}.FLAug"
    return names


# ---------------------------------------------------------------------------
# Score loading
# ---------------------------------------------------------------------------

def load_score(run_name: str):
    """(mean, margin) of model_global_ndcg, or None if the run is absent."""
    path = os.path.join(RUNS_DIR, run_name, 'model_overall_stats.json')
    if not os.path.exists(path):
        return None
    with open(path, 'r', encoding='utf-8') as f:
        stats = json.load(f)['model_global_ndcg']
    return stats['mean'], stats['margin']


# ---------------------------------------------------------------------------
# LaTeX helpers
# ---------------------------------------------------------------------------

def tt(code: str) -> str:
    """Run code for \\texttt{}: braces each hyphen so LaTeX does not ligature
    consecutive ones into en/em dashes."""
    return code.replace('-', '{-}')


def fmt_margin(margins) -> str:
    """The row's 95% CI half-widths as a range, collapsing to a single value
    only when the row's cells genuinely agree to 3 decimal places."""
    if not margins:
        return '---'
    lo, hi = min(margins), max(margins)
    if f'{lo:.3f}' == f'{hi:.3f}':
        return f'{lo:.3f}'
    return f'{lo:.3f}{{-}}{hi:.3f}'


def fmt(value, bold: bool) -> str:
    if value is None:
        return '---'
    text = f'{value:.4f}'
    return f'\\textbf{{{text}}}' if bold else text


# ---------------------------------------------------------------------------
# Table construction
# ---------------------------------------------------------------------------

def build_row_data(qf: str):
    """One dict per ROWS entry: scores per column, the row's margin, and the
    column holding the row maximum."""
    out = []
    for row in ROWS:
        names = run_names(row, qf)
        scores, margins, pending = {}, [], []
        for col in COLUMNS:
            name = names.get(col)
            if name is None:
                scores[col] = None
                continue
            result = load_score(name)
            if result is None:
                scores[col] = None
                hint = pending_hint(name)
                if hint is not None:
                    pending.append(hint)
                continue
            scores[col], margin = result[0], result[1]
            margins.append(margin)

        present = {c: v for c, v in scores.items() if v is not None}
        best = max(present, key=present.get) if present else None
        out.append({
            'row': row,
            'scores': scores,
            # Margins are reported once per row rather than once per cell:
            # repeating them in all six columns spends most of the table width
            # on them. They are NOT near-constant within a row, though -- the
            # ALLFL baselines span ~0.04 -- so the column carries the observed
            # range, not an average that would understate that spread.
            'margins': margins,
            'best': best,
            'pending': pending,
        })
    return out


def render_table(qf: str, data) -> str:
    meta = QUERY_FIELDS[qf]
    lines = []
    lines.append('\\begin{table*} [t]')
    lines.append('\\centering')
    lines.append(
        f"\\caption{{nDCG@5, {meta['label']} queries, uniform sampling (U5, 30-seed random "
        'protocol). Columns escalate the amount of folder-label augmentation applied to the '
        'document side: \\textbf{FL-aug: ALLFL partner} augments only the separate '
        "all-folders-label ranker's labels; \\textbf{FL-aug: doc.\\ field} augments the main "
        "ranker's own \\texttt{folderlabel} field (and, for the hybrid rows, the partner as "
        'well). \\textbf{+HyDE} expands the query with hypothetical documents and a '
        'hypothetical folder label; \\textbf{+CT} expands it with the topic\'s core themes and '
        'related concepts --- these are two different expansions. Bold marks the highest value '
        'in each row; no significance testing is applied, so bold indicates only the larger '
        'number and not a demonstrated difference. The $\\pm$ column gives the range of the '
        '95\\% confidence half-widths across that row\'s cells, reported once per row rather '
        'than repeated in every column. Note that these half-widths are large relative to the '
        'differences between columns. \\texttt{---} marks a cell with no run behind it, either '
        'because the configuration does not exist for that row (the partner columns for '
        'non-hybrid rows, the doc.\\ field columns for the pure-ALLFL rows) or because it has '
        'not been generated yet.}'
    )
    lines.append(f'\\label{{tab:fl-{qf.replace("-", "")}}}')
    lines.append('\\resizebox{\\textwidth}{!}{')
    lines.append('\\begin{tabular}{| l || c | c || c | c || c | c | c || c |}')
    lines.append('\\hline')
    lines.append('\\multicolumn{1}{|c||}{} &')
    lines.append('\\multicolumn{2}{c||}{\\textbf{Plain folder label}} &')
    lines.append('\\multicolumn{2}{c||}{\\textbf{FL-aug: ALLFL partner}} &')
    lines.append('\\multicolumn{3}{c||}{\\textbf{FL-aug: doc.\\ field}} &')
    lines.append('\\multicolumn{1}{c|}{} \\\\')
    lines.append('\\hline')
    lines.append('\\textbf{Configuration} & \\textbf{Base} & \\textbf{+HyDE} & '
                 '\\textbf{Base} & \\textbf{+CT} & '
                 '\\textbf{Base} & \\textbf{+HyDE} & \\textbf{+CT} & '
                 '$\\pm$ \\\\')
    lines.append('\\hline')

    pending_notes = []
    for block in BLOCK_ORDER:
        for entry in [d for d in data if d['row']['block'] == block]:
            cells = [fmt(entry['scores'][c], c == entry['best']) for c in COLUMNS]
            margin = fmt_margin(entry['margins'])
            lines.append(
                f"\\texttt{{{tt(entry['row']['suffix'])}}} & " + ' & '.join(cells)
                + f' & {margin} \\\\'
            )
            pending_notes.extend(entry['pending'])
        lines.append('\\hline')

    lines.append('\\end{tabular}')
    lines.append('}')
    for hint in dict.fromkeys(pending_notes):
        lines.append(f'% TODO: missing cells above -- {hint}')
    lines.append('\\end{table*}')
    return '\n'.join(lines)


def render_summary(all_data, top_n: int = 5) -> str:
    """Cross-query-field table: for each of the strongest configurations, the
    best score per query field, labelled with the variant that produced it."""
    best_by_row = []
    for idx, row in enumerate(ROWS):
        per_qf = {}
        for qf in QUERY_FIELDS:
            entry = all_data[qf][idx]
            if entry['best'] is not None:
                per_qf[qf] = (entry['scores'][entry['best']], entry['best'])
        if len(per_qf) == len(QUERY_FIELDS):
            mean_best = sum(v[0] for v in per_qf.values()) / len(per_qf)
            best_by_row.append((mean_best, row, per_qf))
    best_by_row.sort(key=lambda x: -x[0])
    selected = best_by_row[:top_n]

    lines = []
    lines.append('\\begin{table} [t]')
    lines.append('\\centering')
    lines.append(
        '\\caption{Best-performing variant of each of the strongest configurations, by query '
        'field. Each cell gives the highest nDCG@5 that configuration reached for that query '
        'field, with the variant that produced it in parentheses (see the per-query-field '
        'tables for the full column definitions). The winning variant is not stable across '
        'query fields, which is the reason for reporting it per cell. No significance testing '
        'is applied.}'
    )
    lines.append('\\label{tab:fl-summary}')
    lines.append('\\resizebox{\\columnwidth}{!}{')
    lines.append('\\begin{tabular}{| l || c | c | c |}')
    lines.append('\\hline')
    lines.append('\\textbf{Configuration} & \\textbf{T{-}{-}} & \\textbf{TD-} & '
                 '\\textbf{TDN} \\\\')
    lines.append('\\hline')
    for _, row, per_qf in selected:
        cells = []
        for qf in QUERY_FIELDS:
            score, col = per_qf[qf]
            cells.append(f'{score:.4f} \\small{{({COLUMN_SHORT[col]})}}')
        lines.append(f"\\texttt{{{tt(row['suffix'])}}} & " + ' & '.join(cells) + ' \\\\')
    lines.append('\\hline')
    lines.append('\\end{tabular}')
    lines.append('}')
    lines.append('\\end{table}')
    return '\n'.join(lines)


def write_preview() -> str:
    """Writes the standalone wrapper next to the fragment it renders."""
    fragment = os.path.basename(OUT_PATH)
    with open(PREVIEW_PATH, 'w', encoding='utf-8') as f:
        f.write(PREVIEW_TEMPLATE % {
            'fragment': fragment,
            'fragment_tt': fragment.replace('_', r'\_'),
        })
    return PREVIEW_PATH


def compile_preview() -> bool:
    """Compiles the preview to PDF, leaving the .aux/.log clutter in a temp
    directory rather than in all_runs/. Returns False if pdflatex is absent."""
    if shutil.which('pdflatex') is None:
        print('  pdflatex not found on PATH -- wrote the preview .tex but did '
              'not compile it')
        return False

    with tempfile.TemporaryDirectory() as tmp:
        for path in (OUT_PATH, PREVIEW_PATH):
            shutil.copy(path, tmp)
        result = subprocess.run(
            ['pdflatex', '-interaction=nonstopmode', '-halt-on-error',
             os.path.basename(PREVIEW_PATH)],
            cwd=tmp, capture_output=True, text=True,
        )
        log_path = os.path.join(tmp, os.path.splitext(os.path.basename(PREVIEW_PATH))[0] + '.log')
        if result.returncode != 0:
            print(f'  pdflatex failed (exit {result.returncode}):')
            if os.path.exists(log_path):
                with open(log_path, 'r', encoding='utf-8', errors='replace') as f:
                    errors = [ln.rstrip() for ln in f if ln.startswith('!')]
                for line in errors[:10]:
                    print(f'    {line}')
            return False

        produced = os.path.join(tmp, os.path.splitext(os.path.basename(PREVIEW_PATH))[0] + '.pdf')
        shutil.copy(produced, PREVIEW_PDF)

    print(f'  compiled -> {PREVIEW_PDF}')
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[3])
    parser.add_argument('--preview', action='store_true',
                        help='also write a standalone .tex wrapper that renders the tables')
    parser.add_argument('--compile', dest='do_compile', action='store_true',
                        help='compile the preview to PDF (implies --preview; needs pdflatex)')
    args = parser.parse_args()

    all_data = {qf: build_row_data(qf) for qf in QUERY_FIELDS}

    widest = max(
        ((max(e['margins']) - min(e['margins']), qf, e['row']['suffix'])
         for qf, data in all_data.items() for e in data if e['margins']),
        default=(0.0, '', ''),
    )
    print(f'  widest within-row margin spread: {widest[0]:.4f} '
          f'({widest[1]} {widest[2]}) -- reported as a range, not averaged')

    parts = [
        '% Generated by src/stats_test/build_results_tables.py -- do not edit by hand.',
        '% Re-run after adding runs to all_runs/ to refresh.',
        '',
    ]
    for qf in QUERY_FIELDS:
        parts.append(render_table(qf, all_data[qf]))
        parts.append('')
    parts.append(render_summary(all_data))
    parts.append('')

    with open(OUT_PATH, 'w', encoding='utf-8') as f:
        f.write('\n'.join(parts))

    total = sum(1 for qf in QUERY_FIELDS for e in all_data[qf]
                for c in COLUMNS if e['scores'][c] is not None)
    print(f'Wrote {OUT_PATH}')
    print(f'  {len(QUERY_FIELDS)} per-query-field tables + 1 summary, '
          f'{len(ROWS)} rows each, {total} populated cells')

    if args.preview or args.do_compile:
        print(f'  wrote preview wrapper -> {write_preview()}')
    if args.do_compile:
        compile_preview()


if __name__ == '__main__':
    main()
