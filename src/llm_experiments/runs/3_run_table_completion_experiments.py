"""
run_table_completion_experiments.py
-----------------------------------
Fills the empty cells of all_runs/tables_folder_label.tex (generated by
src/stats_test/build_results_tables.py). Three groups, 43 experiments, all
under the 'random' protocol (30 seeds from RANDOM_SEED_LIST), U5 only.

  Group 1 -- PLAIN ALLFL BASELINES (4 runs, DELEGATED)
  The pure-ALLFL baselines '-.----.-.b' (BM25) and '-.----.-.e' (embeddings)
  were only ever run for TD. Their T and TDN counterparts are the 'Base'
  column those rows are measured against, so without them two of the three
  tables cannot make their central comparison.
      U5.T--.-.----.-.b     U5.TDN.-.----.-.b
      U5.T--.-.----.-.e     U5.TDN.-.----.-.e

  Group 2 -- HyDE ALLFL BASELINES (6 runs, DELEGATED)
  The same two baselines have no '+HyDE' run for any query field ('-.----.-.c'
  does). This completes the '+HyDE' column for the pure-ALLFL block.
      U5.{T--,TD-,TDN}AUG.-.----.-.b
      U5.{T--,TD-,TDN}AUG.-.----.-.e

  Group 3 -- HyDE x AUGMENTED DOC FOLDER LABEL (33 runs, NEW)
  The only genuinely new axis here. run_all_folders_augmented_experiments.py
  paired the augmented document-side folder label ('TOFAUGS') with the plain
  query and with the CT-expanded query, but never with the HyDE-expanded one.
  That leaves the 'FL-aug: doc. field' block of every table with a Base and a
  +CT column but no +HyDE column, so HyDE and CT cannot be compared under the
  same document-side condition -- the comparison the tables most obviously
  invite. 11 configs (Group A's 4 hybrids + Group B's 7 standalones) x 3 query
  fields.
      U5.T--AUG.V.TOFAUGS.mx--2.b.FLAug   (hybrid, Group A)
      U5.T--AUG.B.TOFAUGS.-.-             (standalone, Group B)

Groups 1 and 2 need no new run logic -- run_new_experiments.py and
run_query_augmentated_experiments.py already register ids for them (their
CONFIGS list grew to 17 entries, covering offsets 16 and 17). This script
delegates to their registered callables rather than reimplementing them, so
there is exactly one definition of how each run is produced. It exists to give
the table's missing cells a single entry point:

    | this script | equivalent direct invocation                          |
    |-------------|-------------------------------------------------------|
    | 3901..3904  | run_new_experiments.py 16 17 76 77                    |
    | 3911..3916  | run_query_augmentated_experiments.py 1046 1047 ...    |
    | 3001..3213  | (new -- no equivalent)                                |

NOT included, deliberately: '+HyDE' against the partner-only augmentation
('*.TOFS.*.FLAug' for the hybrids, '*.-.----.-.{b,c,e}.FLAug' for the pure
ALLFL baselines). Adding it would make all three column blocks a full
{Base, +HyDE, +CT} and complete the factorial, at the cost of 21 more runs. It
is a one-line change -- add GROUP_A/GROUP_C offsets to FL_DOC_OFFSETS below --
but it is not what the tables currently ask for.

On folder-label augmentation in Group 3: for the Group A hybrids BOTH sides are
augmented (the main ranker's own 'folderlabel' field via
folder_label_augmented=True, and the separate ALLFL partner via
all_folders_folder_label_augmented=True). The Group B standalones have no ALLFL
partner at all, so only the main ranker's field is augmented. This mirrors
run_all_folders_augmented_experiments.py exactly, because it calls straight
into it.

Prerequisites (both already generated; this script generates neither):
    data/llm_calls/query_expansion/1_doc_folder_hip/{T,TD,TDN}.json   (HyDE)
    data/llm_calls/folder_label_augmentation/2_folder_context/folders.json

Run from the project root:
    python -m src.llm_experiments.runs.run_table_completion_experiments           # all 43
    python -m src.llm_experiments.runs.run_table_completion_experiments 3001 3002 # specific ids
    python -m src.llm_experiments.runs.run_table_completion_experiments T TD      # those query fields
    python -m src.llm_experiments.runs.run_table_completion_experiments ALLFL     # groups 1 + 2 only
    python -m src.llm_experiments.runs.run_table_completion_experiments FLDOC     # group 3 only

Afterwards, regenerate the tables:
    python src/stats_test/build_results_tables.py --compile
"""

import os
import sys

# run_generator.py / run_new_experiments.py use bare imports (e.g. `from
# run_generator import ...`) and expect to run with /src on sys.path, per
# run_new_experiments.py's own docstring ("Run from the /src directory").
# This script instead runs as `python -m src.llm_experiments.runs....` from
# the project root, so /src is not on sys.path by default -- add it here.
_SRC_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
if _SRC_DIR not in sys.path:
    sys.path.insert(0, _SRC_DIR)

from run_generator import Style  # noqa: E402
from run_new_experiments import (  # noqa: E402
    EXPERIMENTS as BASE_EXPERIMENTS,
    is_experiment_done,
)
from .run_query_augmentated_experiments import (  # noqa: E402
    EXPERIMENTS as HYDE_EXPERIMENTS,
)
from .run_all_folders_augmented_experiments import (  # noqa: E402
    ALL_FOLDERS_CONFIGS,
    GROUP_A_OFFSETS,
    GROUP_B_OFFSETS,
    build_run_folder_name,
    run_all_folders_config,
)

# Group 3 covers every config whose main ranker searches 'folderlabel'
# directly -- i.e. everything that has a 'FL-aug: doc. field' cell to fill.
# Group C (the pure ALLFL baselines) has no main-ranker field, so it is absent.
FL_DOC_OFFSETS = GROUP_A_OFFSETS + GROUP_B_OFFSETS
FL_DOC_CONFIGS = [c for c in ALL_FOLDERS_CONFIGS if c['offset'] in FL_DOC_OFFSETS]

# The HyDE variant, as named by run_query_augmentated_experiments.py and
# accepted by RunGenerator(query_augmentation=...).
HYDE_VARIANT = 'AUG'

# id = 3000 + query_field_offset + config_offset, matching the scheme used by
# the other run scripts.
QUERY_FIELD_ID_OFFSET = {'T': 0, 'TD': 100, 'TDN': 200}
ID_BASE = 3000

# Delegated ids -> the (registry, id) they stand for. Kept explicit rather than
# computed so the mapping in the module docstring stays checkable.
DELEGATED = {
    # Group 1: plain ALLFL baselines, run_new_experiments.py
    3901: (BASE_EXPERIMENTS, 16),   # U5.T--.-.----.-.b
    3902: (BASE_EXPERIMENTS, 17),   # U5.T--.-.----.-.e
    3903: (BASE_EXPERIMENTS, 76),   # U5.TDN.-.----.-.b
    3904: (BASE_EXPERIMENTS, 77),   # U5.TDN.-.----.-.e
    # Group 2: HyDE ALLFL baselines, run_query_augmentated_experiments.py
    3911: (HYDE_EXPERIMENTS, 1046),  # U5.T--AUG.-.----.-.b
    3912: (HYDE_EXPERIMENTS, 1047),  # U5.T--AUG.-.----.-.e
    3913: (HYDE_EXPERIMENTS, 1146),  # U5.TD-AUG.-.----.-.b
    3914: (HYDE_EXPERIMENTS, 1147),  # U5.TD-AUG.-.----.-.e
    3915: (HYDE_EXPERIMENTS, 1246),  # U5.TDNAUG.-.----.-.b
    3916: (HYDE_EXPERIMENTS, 1247),  # U5.TDNAUG.-.----.-.e
}

ALLFL_IDS = sorted(DELEGATED)


def _build_registry():
    """id -> (run_folder_name, callable)."""
    registry = {}

    for exp_id, (source, source_id) in DELEGATED.items():
        registry[exp_id] = source[source_id]

    for query_field, qf_offset in QUERY_FIELD_ID_OFFSET.items():
        for config in FL_DOC_CONFIGS:
            exp_id = ID_BASE + qf_offset + config['offset']
            name = build_run_folder_name(config, query_field, HYDE_VARIANT)
            registry[exp_id] = (
                name,
                (lambda c=config, qf=query_field: run_all_folders_config(c, qf, HYDE_VARIANT)),
            )
    return registry


EXPERIMENTS = _build_registry()

FL_DOC_IDS = sorted(set(EXPERIMENTS) - set(DELEGATED))


def _parse_args(argv):
    """Accepts experiment ids (3001, 3901, ...), query fields (T/TD/TDN), and
    the group keywords ALLFL (groups 1+2) and FLDOC (group 3)."""
    if not argv:
        return sorted(EXPERIMENTS.keys())

    selected = []
    for arg in argv:
        if arg.isdigit():
            selected.append(int(arg))
        elif arg.upper() in QUERY_FIELD_ID_OFFSET:
            qf_offset = QUERY_FIELD_ID_OFFSET[arg.upper()]
            selected.extend(ID_BASE + qf_offset + c['offset'] for c in FL_DOC_CONFIGS)
        elif arg.upper() == 'ALLFL':
            selected.extend(ALLFL_IDS)
        elif arg.upper() == 'FLDOC':
            selected.extend(FL_DOC_IDS)
        else:
            print(f"{Style.WARNING}Warning: unrecognised argument '{arg}', ignoring.{Style.RESET}")
    return sorted(set(selected))


if __name__ == "__main__":
    selected = _parse_args(sys.argv[1:])

    print(f"{Style.BOLD}{Style.CYAN}Running {len(selected)} experiment(s): {selected}{Style.RESET}")
    for exp_id in selected:
        if exp_id in EXPERIMENTS:
            delegated = ' (delegated)' if exp_id in DELEGATED else ''
            print(f"  {exp_id:>4}  {EXPERIMENTS[exp_id][0]}{delegated}")

    for exp_id in selected:
        if exp_id not in EXPERIMENTS:
            print(f"{Style.WARNING}Warning: experiment {exp_id} not found, skipping.{Style.RESET}")
            continue
        name, fn = EXPERIMENTS[exp_id]

        if is_experiment_done(name):
            print(f"{Style.WARNING}> Experiment {exp_id} ({name}) already exists in "
                  f"all_runs, skipping.{Style.RESET}")
            continue

        try:
            fn()
            print(f"{Style.GREEN}> Experiment {exp_id} ({name}) complete.{Style.RESET}\n")
        except Exception as e:
            print(f"{Style.FAIL}> Experiment {exp_id} ({name}) failed: {e}{Style.RESET}\n")
            raise

    print(f"\n{Style.BOLD}{Style.GREEN}All done!{Style.RESET}")
    print("Now regenerate the tables: "
          "python src/stats_test/build_results_tables.py --compile")
